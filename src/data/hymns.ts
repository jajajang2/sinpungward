/** 번호(접두 일치) 또는 제목(부분 일치)으로 찬송가 검색 */
export function searchHymns(query: string, limit = 30): Hymn[] {
  const q = query.trim();
  if (!q) return [];
  const isNumeric = /^\d/.test(q);
  const results = HYMNS.filter((h) => (isNumeric ? h.number.startsWith(q) : h.title.includes(q)));
  return results.slice(0, limit);
}

/** 찾은 찬송가를 "번호 - 제목" 형식으로 (기존 hymn_number 텍스트 필드에 저장) */
export function formatHymn(h: Hymn): string {
  return `${h.number} - ${h.title}`;
}
